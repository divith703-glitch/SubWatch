export function findCatalogEntry(name: string): CatalogEntry | undefined {
  const n = name.toLowerCase().trim();
  return (
    CATALOG.find((e) => e.aliases.includes(n)) ??
    CATALOG.find((e) => e.aliases.some((a) => n.includes(a) && a.length >= 3)) ??
    CATALOG.find((e) => n.includes(e.name.toLowerCase().split(' ')[0]))
  );
}
